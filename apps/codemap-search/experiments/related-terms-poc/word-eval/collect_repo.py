"""저장소 하나에서 고정 시드로 파일을 골라(gin과 같은 줄 수) 정의된 이름과 쓰인 이름을 모은다.

사용법(tree-sitter-language-pack이 있는 Python): python collect_repo.py <저장소 경로> <출력 디렉터리> [목표 줄 수, 기본 23672]
출력:
  sample-files.json  고른 파일과 줄 수, 후보에서 뺀 파일 수(생성·압축·외부 코드)
  definitions.jsonl  정의 위치 하나당 한 줄(collect_words.py와 같은 형식 + language)
  words.json         정의된 이름별 집계
  unit-input.json    개념 단위 판정에 넘길 입력(정의된 이름 + 쓰기만 한 이름 + Go struct 태그)
  summary.json
Go 파일은 검증된 collect_words.collect_go로, 나머지 언어는 languages.collect로 모은다.
"""
import collections
import importlib.metadata
import json
import random
import re
import subprocess
import sys
from pathlib import Path

from tree_sitter_language_pack import get_parser

import collect_words
import languages

TARGET_LINES = 23672  # gin 전체 Go 줄 수
EXCLUDED_DIRECTORIES = {".git", "node_modules", "vendor", "third_party", "third-party", "deps", "dep", "external",
                        "dist", "generated", "__snapshots__"}
EXTENSIONS = {".go": "go", ".py": "python", ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript",
              ".jsx": "javascript", ".ts": "typescript", ".mts": "typescript", ".cts": "typescript", ".tsx": "tsx",
              ".java": "java", ".cs": "csharp", ".c": "c", ".h": "c", ".cc": "cpp", ".cpp": "cpp", ".cxx": "cpp",
              ".hpp": "cpp", ".hh": "cpp", ".hxx": "cpp", ".rs": "rust", ".php": "php", ".rb": "ruby"}
CPP_EXTENSIONS = {".cc", ".cpp", ".cxx", ".hpp", ".hh", ".hxx"}
GENERATED_MARKER = re.compile(rb"code generated|@generated|do not edit|auto-generated|autogenerated", re.IGNORECASE)
TEST_PATH = re.compile(r"(^|/)(tests?|__tests__|spec|specs|testing|testdata|fixtures)(/|$)|(_test\.go|_test\.py|^test_.*\.py"
                       r"|\.test\.[jt]sx?|\.spec\.[jt]sx?|Tests?\.(java|cs)|_spec\.rb|Test\.php)$")
MINIFIED_LINE_LENGTH = 1000
# 쓰기만 한 이름의 앞에 붙은 패키지·수신자를 읽는 부모 노드(마지막 이름 자식이 그 이름일 때)
QUALIFIED_PARENTS = {"selector_expression", "qualified_type", "member_expression", "attribute", "field_access",
                     "member_access_expression", "scoped_identifier", "scoped_type_identifier", "field_expression",
                     "qualified_identifier", "member_call_expression", "scoped_call_expression", "nested_type_identifier",
                     "scope_resolution", "class_constant_access_expression", "method_invocation", "qualified_name"}


def language_of(path, is_cpp_repository):
    language = EXTENSIONS.get(path.suffix)
    return "cpp" if language == "c" and path.suffix == ".h" and is_cpp_repository else language


def candidate_files(repository):
    """후보 파일과 뺀 이유별 개수. 줄 수도 함께 센다."""
    files, skipped = [], collections.Counter()
    for path in sorted(repository.rglob("*")):
        relative = path.relative_to(repository)
        if not path.is_file() or path.suffix not in EXTENSIONS or EXCLUDED_DIRECTORIES & set(relative.parts[:-1]):
            continue
        source = path.read_bytes()
        if GENERATED_MARKER.search(source[:2048]):
            skipped["generated"] += 1
            continue
        lines = source.decode(errors="replace").splitlines()
        if any(len(line) > MINIFIED_LINE_LENGTH for line in lines):
            skipped["long_lines"] += 1
            continue
        files.append((str(relative), len(lines)))
    return files, skipped


def sample(files, seed, target_lines):
    shuffled = list(files)
    random.Random(seed).shuffle(shuffled)
    chosen, total = [], 0
    for relative, line_count in shuffled:
        if total >= target_lines:
            break
        chosen.append((relative, line_count))
        total += line_count
    return sorted(chosen), total


def main(repository, output_directory, target_lines=TARGET_LINES):
    repository, output_directory = Path(repository).resolve(), Path(output_directory)
    output_directory.mkdir(parents=True, exist_ok=True)
    files, skipped = candidate_files(repository)
    is_cpp_repository = any(Path(f).suffix in CPP_EXTENSIONS for f, _ in files)
    chosen, total_lines = sample(files, f"word-eval-{repository.name}", int(target_lines))
    (output_directory / "sample-files.json").write_text(json.dumps({
        "seed": f"word-eval-{repository.name}", "target_lines": int(target_lines), "sampled_lines": total_lines,
        "candidate_files": len(files), "candidate_lines": sum(n for _, n in files), "skipped": dict(skipped),
        "excluded_directories": sorted(EXCLUDED_DIRECTORIES), "files": [{"file": f, "lines": n} for f, n in chosen],
    }, ensure_ascii=False, indent=1))

    parsers = {}
    definitions, occurrences = [], collections.Counter()
    examples, qualifiers = collections.defaultdict(list), collections.defaultdict(collections.Counter)
    tags, tag_examples = collections.Counter(), collections.defaultdict(list)
    parse_errors = []
    for relative, _ in chosen:
        path = repository / relative
        language = language_of(path, is_cpp_repository)
        parser = parsers.setdefault(language, get_parser(language))
        source = path.read_bytes()
        lines = source.decode(errors="replace").splitlines()
        if language in ("c", "cpp"):
            source = languages.blank_sal_annotations(source)
        tree = parser.parse(source)
        if tree.root_node.has_error:
            parse_errors.append(relative)
        is_test = bool(TEST_PATH.search(relative))
        for node in languages.walk(tree.root_node):
            if node.type in languages.NAME_LEAVES:
                name = languages.clean_name(node.text.decode(errors="replace"))
                if not name or name == "_" or not re.fullmatch(r"[\w$]+", name):
                    continue
                occurrences[name] += 1
                line = node.start_point[0] + 1
                if len(examples[name]) < 2 and all(not e.startswith(relative + ":") for e in examples[name]):
                    examples[name].append(f"{relative}:{line}: {lines[line - 1].strip()[:150]}")
                parent = node.parent
                if parent is not None and parent.type in QUALIFIED_PARENTS and parent.named_children \
                        and parent.named_children[-1] == node and parent.named_children[0] != node:
                    qualifiers[name][parent.named_children[0].text.decode(errors="replace")[:40]] += 1
            elif language == "go" and node.type == "field_declaration" and node.child_by_field_name("tag"):
                tag = node.child_by_field_name("tag")
                line = node.start_point[0] + 1
                for match in re.finditer(r'(\w+):"([^"]*)"', tag.text.decode(errors="replace")):
                    for word in [match.group(1)] + [v for v in re.split(r"[,=| ]", match.group(2)) if v and v != "-"]:
                        tags[word] += 1
                        if len(tag_examples[word]) < 2:
                            tag_examples[word].append(f"{relative}:{line}: {lines[line - 1].strip()[:150]}")
        if language == "go":
            found = [(n, k, r, o, l, collect_words.text_of(n, source)) for n, k, r, o, l in collect_words.collect_go(tree, source)]
        else:
            found = languages.collect(language, tree, source)
        for name_node, kind, role, owner, is_local, name in found:
            definitions.append({
                "name": name, "kind": kind, "role": role, "scope": "local" if is_local else "package", "owner": owner,
                "file": relative, "line": name_node.start_point[0] + 1, "column": name_node.start_point[1] + 1,
                "language": language, "is_test": is_test, "is_generated": False, "parts": collect_words.parts_of(name),
            })

    kinds = collections.defaultdict(collections.Counter)
    for record in definitions:
        kinds[record["name"]][record["kind"]] += 1
    with open(output_directory / "definitions.jsonl", "w") as handle:
        for record in definitions:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
    words = sorted(({"name": name, "parts": collect_words.parts_of(name), "kinds": dict(kinds[name]),
                     "definition_count": sum(kinds[name].values()), "occurrence_count": occurrences[name]}
                    for name in kinds), key=lambda w: (-w["occurrence_count"], w["name"]))
    (output_directory / "words.json").write_text(json.dumps(words, ensure_ascii=False, indent=1))

    items = [{"name": name, "where": "defined" if name in kinds else "used_only",
              "kinds": dict(kinds[name]) if name in kinds else None,
              "qualifiers": [q for q, _ in qualifiers[name].most_common(3)] or None,
              "count": count, "examples": examples[name]} for name, count in occurrences.items()]
    items += [{"name": word, "where": "struct_tag", "kinds": None, "qualifiers": None, "count": count,
               "examples": tag_examples[word]} for word, count in tags.items()]
    items.sort(key=lambda x: (x["name"].lower(), x["where"]))
    (output_directory / "unit-input.json").write_text(json.dumps(items, ensure_ascii=False, indent=1))

    commit = subprocess.run(["git", "-C", str(repository), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    summary = {
        "repository": str(repository), "commit": commit,
        "tree_sitter": importlib.metadata.version("tree-sitter"),
        "tree_sitter_language_pack": importlib.metadata.version("tree-sitter-language-pack"),
        "sampled_files": len(chosen), "sampled_lines": total_lines, "candidate_files": len(files),
        "languages": dict(collections.Counter(language_of(repository / f, is_cpp_repository) for f, _ in chosen)),
        "parse_error_files": len(parse_errors),
        "definition_count": len(definitions), "defined_names": len(kinds), "used_only_names": sum(1 for i in items if i["where"] == "used_only"),
        "struct_tag_words": len(tags), "unit_input_items": len(items),
        "definitions_by_kind": dict(collections.Counter(r["kind"] for r in definitions).most_common()),
    }
    (output_directory / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1))
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main(*sys.argv[1:4])
